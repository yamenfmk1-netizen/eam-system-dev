const BASE_TRANSLATIONS: Record<string, string> = Object.fromEntries(
  Object.keys(dictionary.ar).map((key) => {
    const k = key as keyof typeof dictionary.ar;
    return [dictionary.ar[k], dictionary.en[k]];
  })
);

const EXACT_TRANSLATIONS: Record<string, string> = {
  ...BASE_TRANSLATIONS,
  ...EXTRA_TRANSLATIONS,
};

const ARABIC_DIGITS: Record<string, string> = {
  '٠': '0', '١': '1', '٢': '2', '٣': '3', '٤': '4',
  '٥': '5', '٦': '6', '٧': '7', '٨': '8', '٩': '9',
};

function latinizeDigits(value: string) {
  return value
    .replace(/[٠-٩]/g, (d) => ARABIC_DIGITS[d] ?? d)
    .replace(/[\u200e\u200f\u061c]/g, '');
}

function translateDynamic(value: string): string | null {
  let m: RegExpMatchArray | null;

  if ((m = value.match(/^مبنى رقم\s+(.+)$/))) return `Building No. ${m[1]}`;
  if ((m = value.match(/^مبنى\s+([0-9٠-٩A-Za-zأ-ي.-]+)$/))) return `Building ${latinizeDigits(m[1])}`;
  if ((m = value.match(/^هل أنت متأكد من حذف\s+["“](.+)["”]؟$/))) return `Are you sure you want to delete “${m[1]}”?`;
  if ((m = value.match(/^هل أنت متأكد من حذف\s+(.+)$/))) return `Are you sure you want to delete ${m[1]}?`;
  if ((m = value.match(/^(.+)\s+في\s+(.+)\s+—\s+موعدها\s+(.+)$/))) return `${m[1]} in ${m[2]} — due ${latinizeDigits(m[3])}`;
  if ((m = value.match(/^(.+)\s+في\s+(.+)\s+—\s+موعده\s+(.+)$/))) return `${m[1]} in ${m[2]} — due ${latinizeDigits(m[3])}`;
  if ((m = value.match(/^(.+)\s+—\s+الكمية المتوفرة\s+\((.+)\)\s+وصلت أو تجاوزت الحد الأدنى\s+\((.+)\)$/))) {
    return `${m[1]} — available quantity (${latinizeDigits(m[2])}) is at or below minimum stock (${latinizeDigits(m[3])})`;
  }
  if ((m = value.match(/^(\d+|[٠-٩]+)\s+يوم متبقٍ$/))) return `${latinizeDigits(m[1])} day(s) left`;
  if ((m = value.match(/^(\d+|[٠-٩]+)\s+يوم منذ الانتهاء$/))) return `${latinizeDigits(m[1])} day(s) since expiry`;
  if ((m = value.match(/^مبنى رقم\s+(.+)\s+·\s+(.+)$/))) return `Building No. ${m[1]} · ${m[2]}`;

  // Dates or counters rendered with Arabic-Indic numerals.
  if (/[٠-٩]/.test(value)) return latinizeDigits(value);

  return null;
}

export function translateUiText(value: string): string {
  if (!value) return value;
  const leading = value.match(/^\s*/)?.[0] ?? '';
  const trailing = value.match(/\s*$/)?.[0] ?? '';
  const core = value.trim();
  if (!core) return value;

  const exact = EXACT_TRANSLATIONS[core];
  if (exact) return `${leading}${exact}${trailing}`;

  // Handle required labels whose source includes an asterisk but map may not.
  if (core.endsWith(' *')) {
    const base = core.slice(0, -2).trim();
    const baseTranslated = EXACT_TRANSLATIONS[base] ?? translateDynamic(base);
    if (baseTranslated) return `${leading}${baseTranslated} *${trailing}`;
  }

  const dynamic = translateDynamic(core);
  if (dynamic) return `${leading}${dynamic}${trailing}`;

  return value;
}
